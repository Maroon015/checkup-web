-- V1: the core tables. Flyway runs each V<number>__*.sql file once, in order, and records
-- it in the flyway_schema_history table. Never edit a migration after it has run;
-- add a new V2__..., V3__... file instead. This is how real teams change a live database.
--
-- Written in standard SQL that works on both H2 (development) and PostgreSQL (production).

CREATE TABLE clinics (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    street_address  VARCHAR(200) NOT NULL,
    city            VARCHAR(100) NOT NULL
);

-- Speeds up "find clinics in my city".
CREATE INDEX idx_clinics_city ON clinics (city);

CREATE TABLE doctors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50)  NOT NULL,
    specialty   VARCHAR(100) NOT NULL,
    email       VARCHAR(254) NOT NULL UNIQUE,
    phone       VARCHAR(10)  NOT NULL,
    fax         VARCHAR(10),
    clinic_id   BIGINT       NOT NULL REFERENCES clinics (id)
);

CREATE TABLE patients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(50)  NOT NULL,
    last_name        VARCHAR(50)  NOT NULL,
    email            VARCHAR(254) NOT NULL UNIQUE,
    date_of_birth    DATE         NOT NULL,
    city             VARCHAR(100),
    street           VARCHAR(100),
    unit_number      VARCHAR(10),
    blood_type       VARCHAR(20)
        CHECK (blood_type IN ('A_POSITIVE','A_NEGATIVE','B_POSITIVE','B_NEGATIVE',
                              'AB_POSITIVE','AB_NEGATIVE','O_POSITIVE','O_NEGATIVE')),
    height_cm        DOUBLE PRECISION CHECK (height_cm > 0),
    weight_kg        DOUBLE PRECISION CHECK (weight_kg > 0),
    medical_history  VARCHAR(2000)
);

CREATE TABLE phone_numbers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    phone_type  VARCHAR(20) NOT NULL CHECK (phone_type IN ('PERSONAL','EMERGENCY')),
    number      VARCHAR(10) NOT NULL
);

CREATE TABLE appointments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT       NOT NULL REFERENCES patients (id),
    doctor_id   BIGINT       NOT NULL REFERENCES doctors (id),
    start_time  TIMESTAMP    NOT NULL,
    end_time    TIMESTAMP    NOT NULL,
    reason      VARCHAR(500) NOT NULL,
    status      VARCHAR(20)  NOT NULL
        CHECK (status IN ('REQUESTED','CONFIRMED','COMPLETED','CANCELLED')),
    created_at  TIMESTAMP    NOT NULL,
    CHECK (end_time > start_time)
);

-- Speeds up "this doctor's schedule" and "my appointments".
-- (The no-double-booking rule is added in step 4, the scheduling step.)
CREATE INDEX idx_appointments_doctor_start ON appointments (doctor_id, start_time);
CREATE INDEX idx_appointments_patient ON appointments (patient_id);
