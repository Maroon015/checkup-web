-- V4: audit log, clinical notes, job applications.

-- ---------------------------------------------------------------------------------------
-- Audit log: who looked at or changed a patient's record, and when.
-- Health-privacy laws (PHIPA in Ontario) expect this for electronic health records, and
-- patients can ask who accessed their information.
--
-- Append-only: the app only ever INSERTs here (see AuditLogRepository, which has no
-- update or delete methods). Names and roles are copied in, so the entry still reads
-- correctly if the account is later changed or removed.
-- Details hold WHAT kind of change ("Changed: blood type"), never the medical values
-- themselves, so the log doesn't become a second copy of private data.
-- ---------------------------------------------------------------------------------------
CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    TIMESTAMP    NOT NULL,
    actor_user_id  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    actor_name     VARCHAR(120) NOT NULL,
    actor_role     VARCHAR(20)  NOT NULL CHECK (actor_role IN ('PATIENT','DOCTOR','ADMIN')),
    action         VARCHAR(30)  NOT NULL
        CHECK (action IN ('VIEW_RECORD','UPDATE_RECORD','ADD_PHONE','REMOVE_PHONE','ADD_NOTE')),
    patient_id     BIGINT       REFERENCES patients (id) ON DELETE SET NULL,
    details        VARCHAR(500)
);
CREATE INDEX idx_audit_patient_time ON audit_log (patient_id, occurred_at);
CREATE INDEX idx_audit_time ON audit_log (occurred_at);

-- Clinical notes: what a doctor writes in a patient's chart. Append-only like a real
-- chart: a mistake is fixed with a new note, not by rewriting history.
CREATE TABLE clinical_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT        NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    doctor_id   BIGINT        NOT NULL REFERENCES doctors (id),
    created_at  TIMESTAMP     NOT NULL,
    body        VARCHAR(4000) NOT NULL
);
CREATE INDEX idx_notes_patient ON clinical_notes (patient_id, created_at);

-- Job applications from the public careers page (was applicationInfo.txt, "protected"
-- by a random access code printed on screen; now only ADMIN accounts can read them).
CREATE TABLE job_applications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(100) NOT NULL,
    email             VARCHAR(254) NOT NULL,
    phone             VARCHAR(10)  NOT NULL,
    position          VARCHAR(30)  NOT NULL CHECK (position IN ('SURGEON','PHARMACIST','DOCTORS_ASSISTANT')),
    years_experience  INT          NOT NULL CHECK (years_experience BETWEEN 2 AND 60),
    availability      VARCHAR(200) NOT NULL,
    submitted_at      TIMESTAMP    NOT NULL
);
