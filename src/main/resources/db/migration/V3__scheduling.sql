-- V3: scheduling. Doctors' weekly working hours, and the database rule that stops
-- double-booking.

-- Weekly availability, e.g. "Mondays 09:00-12:00 in 30-minute slots".
-- A doctor can have several rows per day (e.g. a morning and an afternoon block).
CREATE TABLE doctor_availability (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id     BIGINT     NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    day_of_week   VARCHAR(9) NOT NULL
        CHECK (day_of_week IN ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    start_time    TIME       NOT NULL,
    end_time      TIME       NOT NULL,
    slot_minutes  INT        NOT NULL CHECK (slot_minutes BETWEEN 5 AND 240),
    CHECK (end_time > start_time)
);
CREATE INDEX idx_availability_doctor ON doctor_availability (doctor_id);

-- ---------------------------------------------------------------------------------------
-- No double-booking, enforced by the DATABASE, not just by Java code.
--
-- Why the database: two patients can click the same 9:00 slot at the same moment. Both
-- requests check "is 9:00 free?" -> both see yes -> both insert. That's a race condition,
-- and an "if" in Java can't stop it, because both checks happen before either insert.
-- A UNIQUE rule in the database can: the second insert fails, guaranteed.
--
-- The catch: a CANCELLED appointment must not block its slot. The usual fix is a
-- "partial index" (UNIQUE ... WHERE status <> 'CANCELLED'), which PostgreSQL supports but
-- H2 does not. The portable trick used here:
--   booked_start = start_time while the appointment is active, NULL once cancelled.
--   UNIQUE treats NULLs as all different, so cancelled rows never collide.
-- ---------------------------------------------------------------------------------------
ALTER TABLE appointments ADD COLUMN booked_start TIMESTAMP;
UPDATE appointments SET booked_start = start_time WHERE status <> 'CANCELLED';

ALTER TABLE appointments ADD CONSTRAINT uq_appointments_doctor_slot  UNIQUE (doctor_id, booked_start);
ALTER TABLE appointments ADD CONSTRAINT uq_appointments_patient_slot UNIQUE (patient_id, booked_start);
-- booked_start may only ever be empty or a copy of start_time.
ALTER TABLE appointments ADD CONSTRAINT chk_appointments_booked_start
    CHECK (booked_start IS NULL OR booked_start = start_time);
