-- V2: login accounts. A new migration instead of editing V1, because V1 may already have
-- run on someone's database (that's the Flyway rule).
--
-- Old version: LoginInfo.txt and doctorPasswords.txt stored usernames and passwords as
-- plain text. Here only a BCrypt *hash* is stored: a one-way scramble, so even someone who
-- reads this table can't get the passwords back.

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254) NOT NULL UNIQUE,   -- the login name
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL CHECK (role IN ('PATIENT','DOCTOR','ADMIN')),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL
);

-- Each patient/doctor profile can belong to one login. UNIQUE = one-to-one.
-- Nullable: a doctor can be listed (e.g. imported) before they have an account.
ALTER TABLE patients ADD COLUMN user_id BIGINT UNIQUE REFERENCES users (id);
ALTER TABLE doctors  ADD COLUMN user_id BIGINT UNIQUE REFERENCES users (id);
